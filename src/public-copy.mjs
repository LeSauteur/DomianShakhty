export function publicCopy(value = "") {
  const text = String(value);
  if (revisions.has(text)) return revisions.get(text);
  return text
    .replace(/([Уу])точня(?:ет|ют)ся(?: по литеру| по актуальной смете| на дату обращения| по запросу| перед просмотром)?/gu, (_, initial) => initial === "У" ? "Уточните у агента" : "— уточните у агента")
    .replace(/; текущий статус актуализируется/gu, "")
    .replace(/\s+— уточните у агента на дату обращения/gu, " — уточните у агента");
}
